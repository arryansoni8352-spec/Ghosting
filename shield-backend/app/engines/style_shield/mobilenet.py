"""MobileNetV1 (width 1.0) in JAX, with ImageNet weights loaded from the Keras HDF5 file.

Architecture: Howard et al. (2017). Padding follows the Keras reference exactly: stride-1 layers
use symmetric padding 1; stride-2 layers pad (0,1),(0,1) before a VALID convolution. Input is
expected in [-1, 1] (Keras 'tf' preprocessing: x / 127.5 - 1). Batch-norm uses stored statistics
(inference mode) with epsilon 1e-3.

Verified against the original Keras model by tests/style_shield/test_mobilenet_port.py using
tests/fixtures/mobilenet_reference.npz (generated by scripts/make_mobilenet_reference.py).
"""
from __future__ import annotations

import pathlib
from functools import partial

import h5py
import jax
import jax.numpy as jnp
import numpy as np
from jax import lax

BN_EPS = 1e-3
# (stride, out_channels) for the 13 depthwise-separable blocks.
BLOCKS = [(1, 64), (2, 128), (1, 128), (2, 256), (1, 256), (2, 512),
          (1, 512), (1, 512), (1, 512), (1, 512), (1, 512), (2, 1024), (1, 1024)]
FEATURE_LAYERS = tuple(f"conv_pw_{i}_relu" for i in range(1, 14))
_DN = ("NHWC", "HWIO", "NHWC")


def _bn_from(f, prefix: str) -> dict:
    g = lambda s: np.asarray(f[f"{prefix}/{prefix}/{s}:0"][()], dtype=np.float32)  # noqa: E731
    return {"gamma": g("gamma"), "beta": g("beta"), "mean": g("moving_mean"), "var": g("moving_variance")}


def load_params(path: pathlib.Path) -> dict:
    """Read Keras tensors into a dict of numpy arrays (kernels kept in HWIO layout)."""
    with h5py.File(path, "r") as f:
        params = {"conv1": {"w": np.asarray(f["conv1/conv1/kernel:0"][()], np.float32)},
                  "conv1_bn": _bn_from(f, "conv1_bn"), "blocks": []}
        for i in range(1, len(BLOCKS) + 1):
            dw = np.asarray(f[f"conv_dw_{i}/conv_dw_{i}/depthwise_kernel:0"][()], np.float32)
            pw = np.asarray(f[f"conv_pw_{i}/conv_pw_{i}/kernel:0"][()], np.float32)
            params["blocks"].append({
                # Keras depthwise (kh, kw, in, 1) -> HWIO with I=1, O=in for feature_group_count=in.
                "dw": np.transpose(dw, (0, 1, 3, 2)),
                "dw_bn": _bn_from(f, f"conv_dw_{i}_bn"),
                "pw": pw,
                "pw_bn": _bn_from(f, f"conv_pw_{i}_bn"),
            })
    return jax.tree_util.tree_map(jnp.asarray, params)


def _conv(x, w, stride: int, pad, groups: int = 1):
    return lax.conv_general_dilated(x, w, window_strides=(stride, stride), padding=pad,
                                    dimension_numbers=_DN, feature_group_count=groups)


def _bn(x, p):
    return (x - p["mean"]) / jnp.sqrt(p["var"] + BN_EPS) * p["gamma"] + p["beta"]


@partial(jax.jit, static_argnames=("last",))
def _trunk(params, x_pm1, last: int) -> dict:
    """Run the network up to block `last` (1..13) and return {layer_name: activation}."""
    out = {}
    x = _conv(x_pm1, params["conv1"]["w"], 2, ((0, 1), (0, 1)))
    x = jax.nn.relu6(_bn(x, params["conv1_bn"]))
    for i, ((stride, _), blk) in enumerate(zip(BLOCKS, params["blocks"]), start=1):
        if i > last:
            break
        pad = ((1, 1), (1, 1)) if stride == 1 else ((0, 1), (0, 1))
        x = _conv(x, blk["dw"], stride, pad, groups=x.shape[-1])
        x = jax.nn.relu6(_bn(x, blk["dw_bn"]))
        x = _conv(x, blk["pw"], 1, ((0, 0), (0, 0)))
        x = jax.nn.relu6(_bn(x, blk["pw_bn"]))
        out[f"conv_pw_{i}_relu"] = x
    return out


def _last_index(layers) -> int:
    idx = [int(name.split("_")[2]) for name in layers]
    return max(idx)


def features(params, x01, layers) -> dict:
    """x01: NHWC array in [0,1]. Returns {layer: NHWC activation} for the requested layers."""
    layers = tuple(layers)
    for name in layers:
        if name not in FEATURE_LAYERS:
            raise ValueError(f"unknown layer '{name}'")
    x = x01 * 2.0 - 1.0
    full = _trunk(params, x, last=_last_index(layers))
    return {name: full[name] for name in layers}


def load_mobilenet_v1(path: pathlib.Path) -> dict:
    return load_params(path)
