"""SqueezeNet v1.1 in JAX, independent of MobileNetV1 — different architecture (Fire modules,
squeeze/expand 1x1+3x3 convolutions with bias and plain ReLU, no batch normalisation) and a
different training/licensing lineage (original Caffe weights, Iandola et al. 2016, DeepScale /
UC Berkeley / Stanford; BSD-2-Clause, confirmed from the original authors' repository).

Used ONLY as an independent evaluator in Phase 3: it is never the model the cloak is optimised
against (that remains MobileNetV1 in optimise.py). This is what makes the cross-model evaluation
meaningful rather than circular.

Input: Caffe-style preprocessing (RGB -> BGR, subtract ImageNet BGR means, no [0,1] scaling) —
matches the original Caffe model and the reference Keras port (rcmalli/keras-squeezenet).

Verified against an authoritative Keras reconstruction by
tests/style_shield/test_squeezenet_port.py using tests/fixtures/squeezenet_reference.npz
(generated by scripts/make_squeezenet_reference.py).
"""
from __future__ import annotations

import pathlib
from functools import partial

import h5py
import jax
import jax.numpy as jnp
import numpy as np
from jax import lax

_DN = ("NHWC", "HWIO", "NHWC")
MEAN_BGR = jnp.array([103.939, 116.779, 123.68], dtype=jnp.float32)

# (squeeze_channels, expand_channels) per fire module, in order.
FIRE_BLOCKS = [
    ("fire2", 16, 64), ("fire3", 16, 64),
    ("fire4", 32, 128), ("fire5", 32, 128),
    ("fire6", 48, 192), ("fire7", 48, 192), ("fire8", 64, 256), ("fire9", 64, 256),
]
# Max-pool (kernel 3, stride 2, VALID) happens after conv1, after fire3, after fire5.
POOL_AFTER = {"conv1", "fire3", "fire5"}
FEATURE_LAYERS = tuple(name for name, _, _ in FIRE_BLOCKS)


def preprocess(x01: jnp.ndarray) -> jnp.ndarray:
    """[0,1] RGB -> Caffe-style preprocessed input (BGR, ImageNet mean-subtracted, 0-255 scale)."""
    x255 = x01 * 255.0
    bgr = x255[..., ::-1]
    return bgr - MEAN_BGR


def _conv(x, w, b, stride=1, padding="SAME"):
    y = lax.conv_general_dilated(x, w, (stride, stride), padding, dimension_numbers=_DN)
    return jax.nn.relu(y + b)


def _maxpool_3_2_valid(x):
    return lax.reduce_window(x, -jnp.inf, lax.max, (1, 3, 3, 1), (1, 2, 2, 1), "VALID")


def _find_kernel_bias(group) -> tuple[np.ndarray, np.ndarray]:
    """Descend through self-referential, version-suffixed sub-groups (e.g. 'fire2/squeeze1x1/
    fire2/squeeze1x1_3/kernel:0') until a group holding 'kernel:0' and 'bias:0' is found.
    Exactly one child is expected at each level; this does not assume a fixed nesting depth,
    since it differs between groups in this file (one level for conv1, two for the fire groups,
    and the suffix itself varies, e.g. '_3' vs fire9's '_1')."""
    if "kernel:0" in group:
        return (np.asarray(group["kernel:0"][()], np.float32),
                np.asarray(group["bias:0"][()], np.float32))
    children = list(group.keys())
    if len(children) != 1:
        raise ValueError(f"expected exactly one child group, found {children}")
    return _find_kernel_bias(group[children[0]])


def load_params(path: pathlib.Path) -> dict:
    with h5py.File(path, "r") as f:
        params = {"conv1": _find_kernel_bias(f["conv1"]), "fires": {}}
        for name, _, _ in FIRE_BLOCKS:
            params["fires"][name] = {
                "squeeze1x1": _find_kernel_bias(f[f"{name}/squeeze1x1"]),
                "expand1x1": _find_kernel_bias(f[f"{name}/expand1x1"]),
                "expand3x3": _find_kernel_bias(f[f"{name}/expand3x3"]),
            }
    return jax.tree_util.tree_map(jnp.asarray, params)


@partial(jax.jit, static_argnames=("last",))
def _trunk(params, x_pre, last: str) -> dict:
    out = {}
    w, b = params["conv1"]
    x = _conv(x_pre, w, b, stride=2, padding="VALID")
    if "conv1" in POOL_AFTER:
        x = _maxpool_3_2_valid(x)
    for name, _, _ in FIRE_BLOCKS:
        fp = params["fires"][name]
        sw, sb = fp["squeeze1x1"]
        s = _conv(x, sw, sb, stride=1, padding="SAME")
        e1w, e1b = fp["expand1x1"]
        e1 = _conv(s, e1w, e1b, stride=1, padding="SAME")
        e3w, e3b = fp["expand3x3"]
        e3 = _conv(s, e3w, e3b, stride=1, padding="SAME")
        x = jnp.concatenate([e1, e3], axis=-1)
        out[name] = x
        if name == last:
            break
        if name in POOL_AFTER:
            x = _maxpool_3_2_valid(x)
    return out


def features(params, x01, layers) -> dict:
    layers = tuple(layers)
    for name in layers:
        if name not in FEATURE_LAYERS:
            raise ValueError(f"unknown layer '{name}'")
    last = FEATURE_LAYERS[max(FEATURE_LAYERS.index(n) for n in layers)]
    x_pre = preprocess(x01)
    full = _trunk(params, x_pre, last=last)
    return {name: full[name] for name in layers}


def load_squeezenet(path: pathlib.Path) -> dict:
    return load_params(path)
