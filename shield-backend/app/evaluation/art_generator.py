"""Procedural sample artwork for Style Shield experiments.

These images are generated by this code from seeds. They are NOT copyrighted artworks, and
they are NOT representative of real paintings. They exist so that experiments can run with
clean licensing and full reproducibility.

Styles are a generator (how marks are made) crossed with a palette (which colours are used).
"""
from __future__ import annotations

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

PALETTES = {
    "warm": [(200, 90, 40), (240, 170, 60), (150, 50, 30), (250, 220, 140), (120, 40, 60)],
    "cool": [(40, 90, 140), (70, 160, 170), (20, 50, 90), (140, 200, 210), (90, 110, 160)],
    "primary": [(220, 30, 30), (30, 60, 200), (250, 220, 20), (20, 20, 20), (245, 245, 240)],
    "pastel": [(240, 200, 220), (200, 230, 210), (210, 210, 240), (250, 240, 200), (190, 210, 230)],
}

# Victim artists A1..A4: each has a fixed generator and palette.
VICTIM_STYLES = {
    "A1": ("washes", "warm"),
    "A2": ("strokes", "cool"),
    "A3": ("facets", "primary"),
    "A4": ("dots", "pastel"),
}

# Candidate target styles T1..T12: all generator x palette combinations from the first
# three palettes (warm, cool, primary) across the four generators.
_GENS = ["washes", "strokes", "facets", "dots"]
_CAND_PALETTES = ["warm", "cool", "primary"]
CANDIDATE_STYLES = {
    f"T{i + 1}": (g, p)
    for i, (g, p) in enumerate((g, p) for g in _GENS for p in _CAND_PALETTES)
}


def _washes(rng: np.random.Generator, size: int, pal: list) -> Image.Image:
    yy, xx = np.mgrid[0:size, 0:size].astype(np.float64) / size
    canvas = np.zeros((size, size, 3))
    bg = np.array(pal[3], dtype=np.float64)
    canvas[:] = bg
    for _ in range(8):
        cx, cy = rng.uniform(0, 1, 2)
        sigma = rng.uniform(0.12, 0.3)
        col = np.array(pal[rng.integers(len(pal))], dtype=np.float64)
        w = np.exp(-((xx - cx) ** 2 + (yy - cy) ** 2) / (2 * sigma ** 2))
        canvas = canvas * (1 - 0.5 * w[..., None]) + col * (0.5 * w[..., None])
    noise = rng.normal(0, 4, size=(size, size, 1))
    canvas = np.clip(canvas + noise, 0, 255).astype(np.uint8)
    return Image.fromarray(canvas).filter(ImageFilter.GaussianBlur(1.0))


def _strokes(rng: np.random.Generator, size: int, pal: list) -> Image.Image:
    img = Image.new("RGB", (size, size), tuple(int(c) for c in np.array(pal[3]) * 0.9 + 25))
    draw = ImageDraw.Draw(img)
    theta0 = rng.uniform(0, np.pi)
    for _ in range(int(size * 1.2)):
        x, y = rng.uniform(0, size, 2)
        ang = theta0 + rng.normal(0, 0.35)
        length = rng.uniform(size * 0.08, size * 0.25)
        dx, dy = np.cos(ang) * length / 2, np.sin(ang) * length / 2
        col = pal[rng.integers(len(pal))]
        draw.line([(x - dx, y - dy), (x + dx, y + dy)], fill=col, width=int(rng.integers(2, 5)))
    return img


def _facets(rng: np.random.Generator, size: int, pal: list) -> Image.Image:
    img = Image.new("RGB", (size, size), (250, 250, 245))
    draw = ImageDraw.Draw(img)
    for _ in range(int(size * 0.35)):
        cx, cy = rng.uniform(0, size, 2)
        n = int(rng.integers(3, 6))
        r = rng.uniform(size * 0.06, size * 0.2)
        angles = np.sort(rng.uniform(0, 2 * np.pi, n))
        pts = [(cx + r * np.cos(a), cy + r * np.sin(a)) for a in angles]
        col = pal[rng.integers(len(pal))]
        draw.polygon(pts, fill=col, outline=(15, 15, 15))
    return img


def _dots(rng: np.random.Generator, size: int, pal: list) -> Image.Image:
    img = Image.new("RGB", (size, size), tuple(pal[3]))
    draw = ImageDraw.Draw(img)
    for _ in range(int(size * 2.2)):
        x, y = rng.uniform(0, size, 2)
        r = rng.uniform(size * 0.015, size * 0.05)
        col = pal[rng.integers(len(pal))]
        draw.ellipse([x - r, y - r, x + r, y + r], fill=col)
    return img


_GENERATORS = {"washes": _washes, "strokes": _strokes, "facets": _facets, "dots": _dots}


def paint(style: str, seed: int, size: int = 128) -> np.ndarray:
    """Return a uint8 RGB array (size x size x 3) for a named style and seed.

    `style` is a victim key (A1..A4), a candidate key (T1..T12), or 'generator:palette'.
    """
    if style in VICTIM_STYLES:
        gen, pal = VICTIM_STYLES[style]
    elif style in CANDIDATE_STYLES:
        gen, pal = CANDIDATE_STYLES[style]
    else:
        raise ValueError(f"unknown style '{style}'")
    if size < 32:
        raise ValueError("minimum size is 32")
    rng = np.random.default_rng(seed)
    img = _GENERATORS[gen](rng, size, PALETTES[pal])
    return np.asarray(img.convert("RGB"), dtype=np.uint8).copy()
