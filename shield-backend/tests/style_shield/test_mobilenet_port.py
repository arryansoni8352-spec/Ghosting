"""The JAX MobileNetV1 port must reproduce the ORIGINAL Keras model's activations.

Reference activations were generated by scripts/make_mobilenet_reference.py in a TensorFlow-Keras
environment and stored in tests/fixtures/mobilenet_reference.npz. Those reference values are checked
in, so this test does not require TensorFlow. It does require the weights file, which is verified by
SHA-256 (downloaded from the registered URL if absent).
"""
import pathlib

import numpy as np
import pytest

pytestmark = pytest.mark.model

from app.engines.style_shield.weights import MOBILENET_V1_NOTOP, ensure_weights

FIXTURE = pathlib.Path(__file__).resolve().parents[1] / "fixtures" / "mobilenet_reference.npz"


@pytest.fixture(scope="module")
def params():
    from tests.conftest import require_model_weights
    path = require_model_weights()
    from app.engines.style_shield.mobilenet import load_mobilenet_v1
    return load_mobilenet_v1(path)


@pytest.mark.parametrize("layer", ["conv_pw_2_relu", "conv_pw_3_relu", "conv_pw_5_relu",
                                   "conv_pw_7_relu", "conv_pw_13_relu"])
def test_activations_match_keras_reference(params, layer):
    from app.engines.style_shield.mobilenet import features
    ref = np.load(FIXTURE)
    x01 = ref["input_uint8"].astype(np.float32) / 255.0
    got = np.asarray(features(params, x01, (layer,))[layer])
    expected = ref[layer]
    assert got.shape == expected.shape
    # float32 accumulation differences only; reference maxima are ~6.0 (ReLU6 saturation)
    assert np.max(np.abs(got - expected)) < 1e-3


def test_unknown_layer_rejected(params):
    from app.engines.style_shield.mobilenet import features
    with pytest.raises(ValueError):
        features(params, np.zeros((1, 32, 32, 3), np.float32), ("conv_pw_99_relu",))


def test_output_shapes_for_128px(params):
    from app.engines.style_shield.mobilenet import features
    out = features(params, np.zeros((1, 128, 128, 3), np.float32), ("conv_pw_7_relu",))
    assert out["conv_pw_7_relu"].shape == (1, 8, 8, 512)
